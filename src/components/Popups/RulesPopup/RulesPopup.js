/**
 * Props:
 * - open (boolean): whether the dialog is open
 * - onClose (function): callback when the dialog should close
 * - title? (string): optional title text
 */
export default function RulesPopup({ open, onClose, title = "Правила сайту" }) {
  return (
    <Dialog
      open={open}
      onClose={onClose}
      fullWidth
      maxWidth="md"
      scroll="paper"
      PaperProps={{
        style: {
          borderRadius: "15px",
          backgroundColor: "#fff",
          boxShadow: "0 4px 20px rgba(0, 0, 0, 0.1)",
        },
      }}
      slotProps={{
        backdrop: {
          sx: {
            backdropFilter: "blur(8px)",
          },
        },
      }}
    >
      <DialogTitle
        sx={{
          fontWeight: "bold",
          display: "flex",
          alignItems: "center",
          justifyContent: "space-between",
          pr: 1,
        }}
      >
        {title}
        <IconButton aria-label="Закрити" onClick={onClose} size="small">
          <CloseIcon />
        </IconButton>
      </DialogTitle>
      <DialogContent dividers>
        <Box
          sx={{
            color: "#333",
            fontSize: "0.9rem",
            lineHeight: 1.6,
            "& h3": {
              fontSize: "1.05rem",
              fontWeight: 600,
              color: "#1a1a1a",
              mt: 3,
              mb: 1,
            },
            "& h3:first-of-type": { mt: 0 },
            "& p": { m: 0, mb: 1.25 },
            "& ul": { mt: 0, mb: 1.5, pl: 3 },
            "& li": { mb: 0.5 },
          }}
        >
          {RULES_SECTIONS.map((section) => (
            <section key={section.heading}>
              <h3>{section.heading}</h3>
              {section.blocks.map((block, index) => {
                if (block.text) {
                  return <p key={index}>{block.text}</p>;
                }

                if (block.sub) {
                  return (
                    <Box
                      key={index}
                      sx={{ pl: 2, mb: 1.5, "& p": { mb: 0.75 } }}
                    >
                      {block.sub.map((item, subIndex) => (
                        <p key={subIndex}>{item}</p>
                      ))}
                    </Box>
                  );
                }

                if (block.list) {
                  return (
                    <ul key={index}>
                      {block.list.map((item, listIndex) => (
                        <li key={listIndex}>{item}</li>
                      ))}
                    </ul>
                  );
                }

                return null;
              })}
            </section>
          ))}
        </Box>
      </DialogContent>
    </Dialog>
  );
}
